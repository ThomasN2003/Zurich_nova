def show_feature_chart(
    importance_data,
    title,
):
    """Display model feature importance if available."""

    st.subheader(title)

    if (
        importance_data is None
        or importance_data.empty
    ):
        st.info(
            "Feature-importance information is unavailable. "
            "Run training.py again to generate it."
        )
        return

    chart_data = (
        importance_data
        .head(10)
        .set_index("feature")[["importance"]]
    )

    st.bar_chart(
        chart_data,
        horizontal=True,
        color="#2167d5",
    )

    st.caption(
        "This chart shows overall model importance across "
        "the training dataset. It does not prove that an "
        "individual feature caused a particular result."
    )


