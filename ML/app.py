def format_label(value):
    """Convert stored values into readable labels."""

    return (
        str(value)
        .replace("_", " ")
        .title()
    )


def get_bmi_category(bmi):
    """Return a descriptive BMI band."""

    if bmi < 18.5:
        return "Underweight"

    if bmi < 25:
        return "Healthy range"

    if bmi < 30:
        return "Overweight"

    return "Obese range"


def display_customer_form(
    form_key,
    button_text,
    include_treatment_cost=False,
):
    """Display shared customer-input fields."""

    with st.form(form_key):
        column_1, column_2, column_3 = (
            st.columns(3)
        )

        with column_1:
            age = st.number_input(
                "Age",
                min_value=18,
                max_value=100,
                value=35,
                step=1,
                key=f"{form_key}_age",
            )

            gender = st.selectbox(
                "Gender",
                ["male", "female"],
                format_func=format_label,
                key=f"{form_key}_gender",
            )

        with column_2:
            bmi = st.number_input(
                "Body mass index (BMI)",
                min_value=10.0,
                max_value=70.0,
                value=27.5,
                step=0.1,
                key=f"{form_key}_bmi",
            )

            children = st.number_input(
                "Number of children",
                min_value=0,
                max_value=20,
                value=0,
                step=1,
                key=f"{form_key}_children",
            )

        with column_3:
            discount_eligibility = st.selectbox(
                "Discount eligible",
                ["no", "yes"],
                format_func=format_label,
                key=f"{form_key}_discount",
            )

            region = st.selectbox(
                "Region",
                [
                    "northeast",
                    "northwest",
                    "southeast",
                    "southwest",
                ],
                format_func=format_label,
                key=f"{form_key}_region",
            )

        treatment_cost = None

        if include_treatment_cost:
            treatment_cost = st.number_input(
                "Hospital treatment cost",
                min_value=1.0,
                max_value=1_000_000.0,
                value=10_000.0,
                step=100.0,
                format="%.2f",
                help=(
                    "Enter the amount requested by the "
                    "hospital for the treatment."
                ),
                key=f"{form_key}_cost",
            )

        submitted = st.form_submit_button(
            button_text,
            type="primary",
            use_container_width=True,
        )

    return {
        "submitted": submitted,
        "age": int(age),
        "bmi": float(bmi),
        "children": int(children),
        "gender": gender,
        "discount_eligibility": (
            discount_eligibility
        ),
        "region": region,
        "treatment_cost": treatment_cost,
    }


