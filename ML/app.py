def check_ml_api():
    """Check whether the Python ML service is available."""

    try:
        response = requests.get(
            f"{ML_API_URL}/health",
            timeout=3,
        )

        response.raise_for_status()
        return True, response.json()

    except requests.RequestException:
        return False, None


def check_java_api():
    """
    Check whether the Java backend is reachable.

    A 404 response still proves that the Spring server is
    running because the application may not define a root route.
    """

    try:
        response = requests.get(
            JAVA_API_URL,
            timeout=3,
        )

        return True, response.status_code

    except requests.RequestException:
        return False, None


def call_treatment_contribution_api(
    age,
    bmi,
    children,
    gender,
    discount_eligibility,
    region,
    treatment_cost,
):
    """Request a treatment-contribution prediction."""

    payload = {
        "age": int(age),
        "bmi": float(bmi),
        "children": int(children),
        "gender": gender,
        "discount_eligibility": (
            discount_eligibility
        ),
        "region": region,
        "treatment_cost": float(
            treatment_cost
        ),
    }

    response = requests.post(
        (
            f"{ML_API_URL}/predict/"
            "treatment-contribution"
        ),
        json=payload,
        timeout=30,
    )

    response.raise_for_status()
    return response.json()


